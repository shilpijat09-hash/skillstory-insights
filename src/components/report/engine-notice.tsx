import { BookOpen, FlaskConical } from "lucide-react";
import type { AnalysisSource } from "@/types/analysis";
import { cn } from "@/lib/utils";

/** Honest labelling: tells the user when a report is NOT a real AI analysis. */
export function EngineNotice({ source, className }: { source: AnalysisSource; className?: string }) {
  if (source === "crewai") return null;
  const isSample = source === "sample";
  const Icon = isSample ? BookOpen : FlaskConical;
  return (
    <div
      role="note"
      className={cn(
        "flex gap-3 rounded-xl border px-4 py-3 text-sm",
        isSample ? "border-border bg-muted/60" : "border-warning/30 bg-warning-soft",
        className,
      )}
    >
      <Icon className={cn("mt-0.5 size-4 shrink-0", isSample ? "text-muted-foreground" : "text-warning-foreground")} aria-hidden="true" />
      <p className={isSample ? "text-muted-foreground" : "text-warning-foreground"}>
        {isSample ? (
          <>
            <strong className="font-semibold text-foreground">Sample report.</strong> Illustrative data showing what a ResumeIQ
            review looks like. The candidate and company are fictional.
          </>
        ) : (
          <>
            <strong className="font-semibold">Demo result — not an AI analysis.</strong> This report was generated by the
            prototype&apos;s mock engine from your job description. Your resume was stored securely but its content was not
            read. Real reviews will come from the CrewAI agent backend once it&apos;s connected.
          </>
        )}
      </p>
    </div>
  );
}
